// Sort by name length descending so multi-word names win over single-word
// (e.g. "Papua Barat Daya" before "Papua").
const SORTED_LOCATIONS: ReadonlyArray<GeoPoint> = [
  ...LOCATION_TABLE,
  ...WORLD_COUNTRIES,
  ...WORLD_CITIES,
].sort((a, b) => b.name.length - a.name.length);

const WORD_BOUNDARY_CACHE: ReadonlyArray<{ pattern: RegExp; point: GeoPoint }> =
  SORTED_LOCATIONS.map((point) => ({
    point,
    pattern: new RegExp(`\\b${escapeRegex(point.name)}\\b`, "i"),
  }));

function escapeRegex(s: string): string {
  return s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

