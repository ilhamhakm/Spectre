export function extractLocation(
  text: string | null | undefined,
): GeoPoint | null {
  if (!text) return null;

  // First, try matching a specific Jakarta landmark (these win over the
  // generic city/province match because they're more precise).
  for (const landmark of JAKARTA_LANDMARKS) {
    if (landmark.pattern.test(text)) {
      return landmark.point;
    }
  }

  // Fall back to city / province match.
  for (const entry of WORD_BOUNDARY_CACHE) {
    if (entry.pattern.test(text)) {
      return entry.point;
    }
  }
  return null;
}
